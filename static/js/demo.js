/* Replay-curve demo for the SIMLENS project page. No dependencies.
   Data comes from static/js/examples.js (generated by tools/build_examples.py). */
(() => {
  'use strict';
  const EX = window.SIMLENS_EXAMPLES || [];
  const root = document.getElementById('simlens-demo');
  if (!root || !EX.length) return;

  const NS = 'http://www.w3.org/2000/svg';
  const $ = (s) => root.querySelector(s);
  const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
  const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;
  const signed = (v) => (v >= 0 ? '+' : '−') + Math.abs(v).toFixed(2);

  function S(tag, attrs, parent, text) {
    const n = document.createElementNS(NS, tag);
    if (attrs) for (const k in attrs) if (attrs[k] != null) n.setAttribute(k, attrs[k]);
    if (text != null) n.textContent = text;
    if (parent) parent.appendChild(n);
    return n;
  }
  function H(tag, props, parent, text) {
    const n = document.createElement(tag);
    if (props) for (const k in props) {
      if (k === 'class') n.className = props[k];
      else if (props[k] != null) n.setAttribute(k, props[k]);
    }
    if (text != null) n.textContent = text;
    if (parent) parent.appendChild(n);
    return n;
  }
  function clear(n) { while (n.firstChild) n.removeChild(n.firstChild); }
  function smooth(a, w) {
    const h = Math.floor(w / 2), out = new Array(a.length);
    for (let i = 0; i < a.length; i++) {
      let s = 0, c = 0;
      for (let j = Math.max(0, i - h); j <= Math.min(a.length - 1, i + h); j++) { s += a[j]; c++; }
      out[i] = s / c;
    }
    return out;
  }
  function pathFrom(vals, x, y) {
    let d = '';
    for (let i = 0; i < vals.length; i++) d += (i ? 'L' : 'M') + x(i).toFixed(1) + ',' + y(vals[i]).toFixed(1);
    return d;
  }

  const SERIES = {
    gt: { label: 'Actual replay', short: 'Actual', css: '--s-gt' },
    simlens: { label: 'SIMLENS', short: 'SIMLENS', css: '--s-simlens' },
    noaudio: { label: 'SIMLENS without audio', short: 'No audio', css: '--s-noaudio' },
    baseline: { label: 'Baseline', short: 'Baseline', css: '--s-baseline' },
  };

  const state = { i: 0, noaudio: false, baseline: false, t: null, hover: null };
  const chart = $('#demo-chart'), wrap = chart.parentNode, tip = $('#demo-tip'), box = $('#demo-player');
  const cache = new Map();
  let ctx = null, player = null, ytPromise = null, raf = 0, lastTick = 0;

  function visible(ex) {
    const out = ['simlens'];
    if (state.noaudio && ex.series.noaudio) out.push('noaudio');
    if (state.baseline && ex.series.baseline) out.push('baseline');
    return out;
  }
  function data(ex, key) {
    if (key === 'gt') return ex.series.gt;
    const id = ex.id + '|' + key;
    if (!cache.has(id)) cache.set(id, smooth(ex.series[key], 5));
    return cache.get(id);
  }

  // ------------------------------------------------------------ chart
  function draw() {
    const ex = EX[state.i];
    // k follows the page's root font size, so the chart grows with the text on large screens
    const k = (parseFloat(getComputedStyle(document.documentElement).fontSize) || 16) / 16;
    const W = Math.max(280, Math.round(wrap.clientWidth)), wide = W >= 620;
    const m = { l: 36 * k, r: wide ? 84 * k : 10, t: 34 * k, b: 26 * k }, Hh = Math.round((wide ? 300 : 236) * k);
    const T = ex.duration, keys = visible(ex);
    clear(chart);
    chart.setAttribute('viewBox', `0 0 ${W} ${Hh}`); chart.setAttribute('height', Hh);
    let lo = Infinity, hi = -Infinity;
    // The vertical scale covers every curve this video has, shown or hidden,
    // so switching a tag on or off never rescales the chart.
    [ex.series.gt, ...['simlens', 'noaudio', 'baseline'].filter((k) => ex.series[k]).map((k) => data(ex, k))]
      .forEach((a) => a.forEach((v) => { if (v < lo) lo = v; if (v > hi) hi = v; }));
    lo = Math.min(-2, Math.floor(lo)); hi = Math.max(2, Math.ceil(hi));
    const x0 = m.l, x1 = W - m.r, y0 = Hh - m.b, y1 = m.t;
    const x = (i) => x0 + (i / (T - 1)) * (x1 - x0);
    const y = (v) => y0 - ((v - lo) / (hi - lo)) * (y0 - y1);
    ctx = { x, y, x0, x1, y0, y1, T, k };

    const stepY = hi - lo > 7 ? 2 : 1;
    for (let v = Math.ceil(lo / stepY) * stepY; v <= hi; v += stepY) {
      S('line', { class: 'gridline', x1: x0, x2: x1, y1: Math.round(y(v)) + 0.5, y2: Math.round(y(v)) + 0.5 }, chart);
      S('text', { x: x0 - 6 * k, y: y(v) + 4 * k, 'text-anchor': 'end' }, chart, v > 0 ? '+' + v : v < 0 ? '−' + Math.abs(v) : '0');
    }
    S('text', { x: x0, y: 11 * k }, chart, 'Replay intensity, standardised within the video');
    S('line', { class: 'axisline', x1: x0, x2: x1, y1: y0 + 0.5, y2: y0 + 0.5 }, chart);
    const stepX = T <= 150 ? 30 : T <= 330 ? 60 : 120;
    for (let s = 0; s <= T - 1; s += stepX) {
      S('line', { class: 'axisline', x1: x(s), x2: x(s), y1: y0, y2: y0 + 4 * k }, chart);
      S('text', { x: x(s), y: y0 + 17 * k, 'text-anchor': s === 0 ? 'start' : 'middle' }, chart, mmss(s));
    }

    const gt = ex.series.gt;
    S('path', { class: 'gt-area', d: pathFrom(gt, x, y) + `L${x1.toFixed(1)},${y0}L${x0},${y0}Z` }, chart);
    S('path', { class: 'gt-line', d: pathFrom(gt, x, y) }, chart);
    keys.slice().reverse().forEach((k) => S('path', { class: `line s-${k}`, d: pathFrom(data(ex, k), x, y) }, chart));

    if (wide) {   // direct labels with leaders; the row above the chart is the legend
      const items = [{ k: 'gt', v: gt[T - 1] }, ...keys.map((k) => ({ k, v: data(ex, k)[T - 1] }))]
        .map((o) => ({ k: o.k, ya: y(o.v), yl: y(o.v) })).sort((a, b) => a.yl - b.yl);
      const gap = 15 * k;
      for (let i = 1; i < items.length; i++) if (items[i].yl - items[i - 1].yl < gap) items[i].yl = items[i - 1].yl + gap;
      const over = items[items.length - 1].yl - (y0 - 4);
      if (over > 0) items.forEach((o) => { o.yl -= over; });
      for (let i = items.length - 2; i >= 0; i--) if (items[i + 1].yl - items[i].yl < gap) items[i].yl = items[i + 1].yl - gap;
      items.forEach((o) => {
        S('path', { class: `leader s-${o.k}`, d: `M${x1 + 3 * k},${o.ya.toFixed(1)}L${x1 + 11 * k},${o.yl.toFixed(1)}L${x1 + 17 * k},${o.yl.toFixed(1)}` }, chart);
        S('text', { class: 'endlabel', x: x1 + 21 * k, y: o.yl + 4 * k }, chart, SERIES[o.k].short);
      });
    }

    const hv = S('g', { style: 'display:none' }, chart);
    S('line', { class: 'cross', y1, y2: y0 }, hv);
    const ph = S('g', { style: 'display:none' }, chart);
    S('line', { class: 'playhead', y1: y1 - 2, y2: y0 }, ph);
    const tag = S('g', { class: 'playhead-tag' }, ph);
    S('rect', { x: -19 * k, y: y1 - 19 * k, width: 38 * k, height: 16 * k, rx: 4 }, tag);
    S('text', { x: 0, y: y1 - 7.5 * k, 'text-anchor': 'middle' }, tag, '0:00');
    ctx.hv = hv; ctx.ph = ph; ctx.tag = tag;

    const hit = S('rect', { class: 'hit', x: x0, y: y1, width: x1 - x0, height: y0 - y1 }, chart);
    const idxAt = (ev) => {
      const r = chart.getBoundingClientRect();
      return clamp(Math.round(((ev.clientX - r.left - x0) / (x1 - x0)) * (T - 1)), 0, T - 1);
    };
    hit.addEventListener('pointermove', (ev) => setHover(idxAt(ev)));
    hit.addEventListener('pointerleave', () => setHover(null));
    hit.addEventListener('click', (ev) => seek(idxAt(ev)));
    if (state.t != null) setPlayhead(state.t);
    if (state.hover != null) setHover(state.hover);

    // per-video correlation line and optional table
    const rho = $('#demo-rho'); clear(rho);
    rho.appendChild(document.createTextNode('Spearman ρ with the actual curve: '));
    keys.forEach((k, j) => {
      if (j) H('span', { class: 'sep' }, rho, '·');
      rho.appendChild(document.createTextNode(SERIES[k].label + ' '));
      H('b', null, rho, ex.rho[k].toFixed(2));
    });
    drawTable();
  }

  function setHover(i) {
    state.hover = i;
    if (!ctx) return;
    const ex = EX[state.i], hv = ctx.hv;
    if (i == null) { hv.style.display = 'none'; tip.classList.remove('on'); return; }
    hv.style.display = '';
    while (hv.childNodes.length > 1) hv.removeChild(hv.lastChild);
    const xi = ctx.x(i), keys = ['gt', ...visible(ex)];
    hv.firstChild.setAttribute('x1', xi); hv.firstChild.setAttribute('x2', xi);
    keys.forEach((k) => S('circle', { class: `dot f-${k}`, cx: xi, cy: ctx.y(data(ex, k)[i]), r: 4.5 * ctx.k }, hv));
    clear(tip);
    H('div', { class: 'tt-h' }, tip, mmss(i));
    keys.forEach((k) => {
      const r = H('div', { class: 'tt-r' }, tip);
      H('i', { style: `--c:var(${SERIES[k].css})` }, r);
      H('b', null, r, signed(data(ex, k)[i]));
      H('span', null, r, SERIES[k].label);
    });
    H('div', { class: 'tt-f' }, tip, 'Click to play from here');
    tip.classList.add('on');
    const w = tip.offsetWidth, h = tip.offsetHeight, W = wrap.clientWidth;
    let left = xi + 14; if (left + w > W - 4) left = xi - w - 14;
    tip.style.left = clamp(left, 0, Math.max(0, W - w)) + 'px';
    tip.style.top = Math.max(0, Math.min(...keys.map((k) => ctx.y(data(ex, k)[i]))) - h - 10) + 'px';
  }

  function setPlayhead(t) {
    if (!ctx || t == null) return;
    const xi = ctx.x(clamp(t, 0, ctx.T - 1));
    ctx.ph.style.display = '';
    ctx.ph.firstChild.setAttribute('x1', xi); ctx.ph.firstChild.setAttribute('x2', xi);
    ctx.tag.setAttribute('transform', `translate(${clamp(xi, ctx.x0 + 19 * ctx.k, ctx.x1 - 19 * ctx.k).toFixed(1)},0)`);
    ctx.tag.lastChild.textContent = mmss(t);
  }

  function drawTable() {
    const det = $('#demo-table'); if (!det.open) return;
    const ex = EX[state.i], keys = ['gt', ...visible(ex)], holder = det.querySelector('.table-container');
    clear(holder);
    const t = H('table', { class: 'table is-narrow is-fullwidth' }, holder), hr = H('tr', null, H('thead', null, t));
    H('th', { scope: 'col' }, hr, 'Time');
    keys.forEach((k) => H('th', { scope: 'col' }, hr, SERIES[k].label));
    const tb = H('tbody', null, t);
    for (let s = 0; s < ex.duration; s += 5) {
      const tr = H('tr', null, tb);
      H('td', null, tr, mmss(s));
      keys.forEach((k) => H('td', null, tr, signed(data(ex, k)[s])));
    }
  }

  // ------------------------------------------------------------ video
  function facade(ex) {
    clear(box);
    const b = H('button', { class: 'facade', type: 'button', 'aria-label': 'Play video: ' + ex.title }, box);
    H('img', { src: `https://i.ytimg.com/vi/${ex.youtube_id}/hqdefault.jpg`, alt: '', loading: 'lazy' }, b);
    const p = H('span', { class: 'play' }, b), ic = S('svg', { viewBox: '0 0 24 24', 'aria-hidden': 'true' }, p);
    S('path', { d: 'M6 4l14 8-14 8z' }, ic);
    b.addEventListener('click', () => start(ex, state.t || 0));
  }
  function message(ex) {
    clear(box);
    const p = H('p', null, H('div', { class: 'msg' }, box), 'This video cannot be played here. ');
    H('a', { href: `https://www.youtube.com/watch?v=${ex.youtube_id}`, target: '_blank', rel: 'noopener' }, p, 'Watch it on YouTube');
  }
  function loadYT() {
    if (ytPromise) return ytPromise;
    ytPromise = new Promise((res, rej) => {
      if (window.YT && window.YT.Player) return res(window.YT);
      const prev = window.onYouTubeIframeAPIReady;
      window.onYouTubeIframeAPIReady = () => { if (prev) prev(); res(window.YT); };
      const s = H('script', { src: 'https://www.youtube.com/iframe_api' });
      s.onerror = () => { ytPromise = null; rej(new Error('YouTube API failed to load')); };
      document.head.appendChild(s);
    });
    return ytPromise;
  }
  function stop() {
    cancelAnimationFrame(raf);
    if (player && player.destroy) { try { player.destroy(); } catch (e) { /* already gone */ } }
    player = null;
  }
  function start(ex, t) {
    stop(); clear(box);
    const holder = H('div', null, box);
    loadYT().then((YT) => {
      if (EX[state.i] !== ex) return;
      player = new YT.Player(holder, {
        host: 'https://www.youtube-nocookie.com', videoId: ex.youtube_id, width: '100%', height: '100%',
        playerVars: { autoplay: 1, start: Math.floor(t), playsinline: 1, rel: 0 },
        events: {
          onReady: (e) => { try { e.target.playVideo(); } catch (err) { /* autoplay blocked */ } tick(); },
          onError: () => { stop(); message(ex); },
        },
      });
    }).catch(() => message(ex));
  }
  function tick() {
    cancelAnimationFrame(raf);
    const loop = (now) => {
      if (player && player.getCurrentTime && now - lastTick > 80) {
        lastTick = now;
        const t = player.getCurrentTime();
        if (Number.isFinite(t) && (t > 0 || state.t == null)) { state.t = t; setPlayhead(t); }
      }
      raf = requestAnimationFrame(loop);
    };
    raf = requestAnimationFrame(loop);
  }
  function seek(sec) {
    state.t = sec; setPlayhead(sec);
    if (player && player.seekTo) { player.seekTo(sec, true); if (player.playVideo) player.playVideo(); }
    else start(EX[state.i], sec);
  }

  // ------------------------------------------------------------ examples + controls
  const thumbs = $('#demo-thumbs'), cbNo = $('#demo-noaudio'), cbBase = $('#demo-baseline');
  function select(i) {
    state.i = i; state.t = null; state.hover = null;
    const ex = EX[i];
    stop(); facade(ex);
    $('#demo-title').textContent = ex.title;
    const meta = $('#demo-meta'); clear(meta);
    meta.appendChild(document.createTextNode([ex.channel, mmss(ex.duration), ex.set].filter(Boolean).join(' · ') + ' · '));
    H('a', { href: `https://www.youtube.com/watch?v=${ex.youtube_id}`, target: '_blank', rel: 'noopener' }, meta, 'YouTube');
    cbNo.disabled = !ex.series.noaudio; if (cbNo.disabled) { cbNo.checked = false; state.noaudio = false; }
    cbBase.disabled = !ex.series.baseline; if (cbBase.disabled) { cbBase.checked = false; state.baseline = false; }
    Array.from(thumbs.children).forEach((b, j) => b.setAttribute('aria-pressed', j === i ? 'true' : 'false'));
    draw();
  }
  EX.forEach((ex, i) => {
    const b = H('button', { class: 'demo-thumb', type: 'button', 'aria-pressed': 'false', title: ex.title }, thumbs);
    H('img', { src: `https://i.ytimg.com/vi/${ex.youtube_id}/mqdefault.jpg`, alt: ex.title, loading: 'lazy' }, b);
    H('span', null, b, `${ex.category} · ${mmss(ex.duration)}`);
    b.addEventListener('click', () => select(i));
  });
  cbNo.addEventListener('change', () => { state.noaudio = cbNo.checked; draw(); });
  cbBase.addEventListener('change', () => { state.baseline = cbBase.checked; draw(); });
  $('#demo-table').addEventListener('toggle', drawTable);
  chart.addEventListener('keydown', (e) => {
    const ex = EX[state.i], cur = state.hover != null ? state.hover : Math.round(state.t || 0);
    if (e.key === 'ArrowRight' || e.key === 'ArrowLeft') {
      e.preventDefault();
      setHover(clamp(cur + (e.key === 'ArrowRight' ? 1 : -1) * (e.shiftKey ? 10 : 1), 0, ex.duration - 1));
    } else if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); seek(cur); }
    else if (e.key === 'Escape') setHover(null);
  });
  chart.addEventListener('blur', () => setHover(null));

  // Optional deep link: index.html#ex=video_31465&na=1&base=1&t=45
  const q = new URLSearchParams(location.hash.replace(/^#/, ''));
  let first = EX.findIndex((e) => e.id === q.get('ex') || e.youtube_id === q.get('ex'));
  const linked = first >= 0;
  if (!linked) first = 0;
  select(first);
  if (linked) {
    const ex = EX[first];
    if (q.get('na') === '1' && ex.series.noaudio) { state.noaudio = true; cbNo.checked = true; }
    if (q.get('base') === '1' && ex.series.baseline) { state.baseline = true; cbBase.checked = true; }
    const t = parseFloat(q.get('t'));
    if (Number.isFinite(t)) state.t = clamp(t, 0, ex.duration - 1);
    draw();
    const h = parseInt(q.get('h'), 10);
    if (Number.isFinite(h)) setHover(clamp(h, 0, ex.duration - 1));
    if (q.get('play') === '1') start(ex, state.t || 0);
  }

  let pending = 0, lastW = window.innerWidth;
  window.addEventListener('resize', () => {
    if (window.innerWidth === lastW) return;
    lastW = window.innerWidth;
    cancelAnimationFrame(pending); pending = requestAnimationFrame(draw);
  });
})();
